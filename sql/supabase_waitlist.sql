-- BuildPulse research waitlist. Run in Supabase SQL editor.
-- Personal data must remain private; browser clients cannot query this table.
create table if not exists public.buildpulse_waitlist (
  id bigint generated by default as identity primary key,
  email text not null unique check (char_length(email) between 5 and 254),
  trade text not null check (trade in (
    'All trades','Roofing','HVAC','Plumbing','Electrical','Windows & Doors',
    'Concrete','Demolition','New Construction','Renovation'
  )),
  company text,
  requested_plan text not null check (requested_plan in ('not_sure','no','19','39','79','99_plus')),
  wants_pilot boolean not null default false,
  consent_to_contact boolean not null check (consent_to_contact is true),
  created_at timestamptz not null default now()
);
create index if not exists buildpulse_waitlist_created_at_idx
  on public.buildpulse_waitlist (created_at desc);
alter table public.buildpulse_waitlist enable row level security;
revoke all on table public.buildpulse_waitlist from public, anon, authenticated;
revoke all on sequence public.buildpulse_waitlist_id_seq from public, anon, authenticated;
-- No browser insert/select/update/delete RLS policies are created.
-- Only the service-role/secret-key Edge Function is allowed to write.
